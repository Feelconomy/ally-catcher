const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const assert=require('node:assert/strict');
const os=require('node:os');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('https://**/*',r=>r.abort());
  await page.goto(process.env.TEST_URL||'http://127.0.0.1:4178/#home');
  const result=await page.evaluate(()=>{
   Store.state.guest=true;Store.state.coachDone=true;
   const m=MACHINES[0];
   Store.state.settings.skin='classic';
   if(modePicker().includes('data-s="classic"')||adminSkinPicker().includes('data-s="classic"'))throw Error('Classic button visible');
   Store.refillMachine(m,13);render('play',m.id);
   if(Play.skinId!=='arcade'||Play.dolls.length!==13)throw Error('Fallback or count');
   const first=JSON.stringify(Play.dolls);render('play',m.id);
   if(first!==JSON.stringify(Play.dolls))throw Error('Layout moved on reentry');
   const saved=structuredClone(Play.dolls);
   Store.state.stock[m.id].push(saved[0].dollId);
   Store.saveLayout(m,'arcade',[{...saved[0],layer:0,bottom:130},...saved]);
   render('play',m.id);
   if(JSON.stringify(Play.dolls)!==JSON.stringify(saved))throw Error('Migration moved lower rows');
   const rows=new Set(Play.dolls.map(d=>d.layer)).size;
   Store.saveLayout(m,'arcade',[{...saved[0],layer:0,bottom:130}]);
   render('play',m.id);
   if(!Play.dolls.length||Play.dolls.some(d=>d.layer===0))throw Error('Top-row-only migration');
   Play.stop();Play.start(m,'classic');
   if(Play.skinId!=='classic')throw Error('Classic implementation removed');
   render('play',m.id);
   return {rows,count:Play.dolls.length};
  });
  assert.equal(result.rows,3);assert.equal(result.count,13);
  await page.screenshot({path:path.join(os.tmpdir(),'ally-green-three-rows.png')});
  await page.evaluate(()=>{Math.random=()=>.5;Store.state.tickets=10;go('machine',MACHINES[0].id);});
  await page.waitForFunction(()=>App.route==='machine');
  assert.equal(await page.locator('.md-mode').count(),0);
  assert.equal(await page.locator('.md-activity-copy').innerText(),'지금 함께 뽑는 중');
  assert.equal(await page.locator('.md-activity-count strong').innerText(),'6');
  for(const width of [320,390,1440]){
   await page.setViewportSize({width,height:844});
   assert(await page.locator('.md-activity').evaluate(el=>el.scrollWidth<=el.clientWidth));
  }
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(os.tmpdir(),'ally-activity-card.png')});
  await page.locator('[data-act="play"]').click();
  await page.getByRole('heading',{name:'모드를 선택해주세요!'}).waitFor();
  assert.equal(await page.evaluate(()=>Store.state.tickets),10);
  assert.equal(await page.getByRole('button',{name:'취소',exact:true}).count(),0);
  await page.getByRole('button',{name:'닫기',exact:true}).click();
  assert.equal(await page.evaluate(()=>Store.state.tickets),10);
  await page.locator('[data-act="play"]').click();
  await page.getByRole('heading',{name:'모드를 선택해주세요!'}).waitFor();
  await page.waitForTimeout(350);
  await page.screenshot({path:path.join(os.tmpdir(),'ally-mode-dialog.png')});
  const cost=await page.evaluate(()=>MACHINES[0].cost);
  await page.getByRole('button',{name:'기본',exact:true}).click();
  await page.waitForFunction(()=>App.route==='play');
  assert.equal(await page.evaluate(()=>Play.skinId),'arcade');
  assert.equal(await page.evaluate(()=>Store.state.tickets),10-cost);
  await page.evaluate(()=>{go('machine',MACHINES[0].id);window.startGreen3D=()=>{window.didStart3D=true;};});
  await page.waitForFunction(()=>App.route==='machine');
  await page.locator('[data-act="play"]').click();
  await page.getByRole('button',{name:'3D(베타)',exact:true}).click();
  await page.waitForFunction(()=>window.didStart3D);
  assert.equal(await page.evaluate(()=>Store.state.settings.skin),'green3d');
  assert.equal(await page.evaluate(()=>Store.state.tickets),10-2*cost);
  const fallback=await browser.newPage();
  await fallback.route('https://**/*',r=>r.abort());
  await fallback.route('**/js/play3d.js*',r=>r.abort());
  await fallback.goto(process.env.TEST_URL||'http://127.0.0.1:4178/#home');
  await fallback.evaluate(()=>{Store.state.guest=true;Store.state.coachDone=true;Store.state.tickets=7;Store.state.settings.skin='green3d';render('play',MACHINES[0].id);});
  await fallback.getByRole('button',{name:'기본 모드로 계속',exact:true}).click();
  assert.deepEqual(await fallback.evaluate(()=>({skin:Play.skinId,saved:Store.state.settings.skin,tickets:Store.state.tickets,machine:Play.machine.id===MACHINES[0].id})),{skin:'arcade',saved:'arcade',tickets:7,machine:true});
  await fallback.close();
  assert.deepEqual(errors,[]);
  console.log('PASS: mode dialog / cancel / both choices / ticket deduction, classic retained, 13 dolls / 3 rows, layout migration');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
